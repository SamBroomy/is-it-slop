impl PrettyOptions {
    fn any(self) -> bool {
        self.verbose || self.quiet || self.chunks
    }
}

const HEADING_INPUT: &str = "Input";
const HEADING_OUTPUT: &str = "Output";
const HEADING_CLASSIFICATION: &str = "Classification";

/// Run the CLI with the given arguments and return the process exit code.
///
/// Results go to stdout. Documents that cannot be scored are reported by the sink; only setup
/// failures come back as `Err`.
pub fn run(cli: &Cli) -> Result<u8> {
    if cli.output != OutputFormat::Pretty && cli.pretty.any() {
        anyhow::bail!("--verbose, --quiet and --chunks only apply to --output pretty");
    }

    let color = cli.color.enabled();
    let Some(input) = Input::from_cli(cli) else {
        output_welcome(color);
        return Ok(0);
    };
    let mut sink = cli.output.sink(SinkOptions {
        labelled: input.is_multi(),
        color,
        detail: Detail::from_flags(cli.pretty.verbose, cli.pretty.quiet),
        chunks: cli.pretty.chunks,
    });
    let predictor = Predictor::default().with_threshold(cli.threshold);

    let stdout = io::stdout();
    let mut out = stdout.lock();
    match drive(&input, &predictor, sink.as_mut(), &mut out) {
        Ok(summary) => Ok(summary.exit_code(cli.exit_status)),
        // A consumer such as `head` closed the pipe: it got what it asked for.
        Err(e) if is_broken_pipe(&e) => Ok(0),
        Err(e) => Err(e),
    }
}

fn is_broken_pipe(error: &anyhow::Error) -> bool {
    error
        .downcast_ref::<io::Error>()
        .is_some_and(|e| e.kind() == io::ErrorKind::BrokenPipe)
}

/// Documents handed to the predictor per pass; the backend's [`pipeline::Strategy`] decides how
/// a pass is spread over forwards and threads. Bounds memory and how much output waits on the
/// model at once. 256 is the knee of the window sweep on the CPU backend (97% of the plateau,
/// ~85 ms to first output) and holds four of the GPU backend's 64-document passes.
pub const BATCH_SIZE: usize = 256;

/// Stream documents through the model in batches, handing each result to the sink in input
/// order as soon as its batch is scored.
fn drive(
    input: &Input,
    predictor: &Predictor,
    sink: &mut dyn Sink,
    out: &mut dyn Write,
) -> Result<RunSummary> {
    let mut run = Run {
        predictor,
        sink,
        out,
        summary: RunSummary::default(),
        pending: Vec::with_capacity(BATCH_SIZE),
    };
    run.sink.begin(run.out)?;
    for document in input.documents() {
        match document {
            Ok(document) => {
                run.pending.push(document);
                if run.pending.len() == BATCH_SIZE {
                    run.score_pending()?;
                }
            }
            Err(SourceError { id, error }) => {
                // Flush first so the failure lands where the source produced it.
                run.score_pending()?;
                run.emit(&id, &Err(error))?;
            }
        }
    }
    run.score_pending()?;
    run.sink.finish(run.out, &run.summary)?;
    run.out.flush()?;
    Ok(run.summary)
}

/// One run's moving parts: the batch waiting to be scored and where results go.
struct Run<'a> {
    predictor: &'a Predictor,
    sink: &'a mut dyn Sink,
    out: &'a mut dyn Write,
    summary: RunSummary,
    pending: Vec<Document>,
}

impl Run<'_> {
    fn score_pending(&mut self) -> Result<()> {
        let texts: Vec<&str> = self.pending.iter().map(|d| d.text.as_str()).collect();
        let results = pipeline::predict_each(&texts);
        // Swapped out so the buffer keeps its capacity across batches.
        let mut batch = std::mem::take(&mut self.pending);
        let want_chunk_texts = self.sink.wants_chunk_texts();
        for (document, result) in batch.iter().zip(results) {
            let item = result
                .map(|prediction| {
                    let scored = Scored::new(prediction, self.predictor.threshold());
                    if want_chunk_texts {
                        scored.with_chunk_texts(pipeline::chunk_texts(&document.text))
                    } else {
                        scored
                    }
                })
                .map_err(Into::into);
            self.emit(&document.id, &item)?;
        }
        batch.clear();
        self.pending = batch;
        Ok(())
    }

    fn emit(&mut self, id: &DocumentId, item: &Item) -> Result<()> {
        match item {
            Ok(scored) => self.sink.emit(self.out, id, scored)?,
            Err(error) => self.sink.emit_error(self.out, id, error)?,
        }
        self.summary.record(item);
        Ok(())
    }
}
